//! Capability-benchmark registry (CH-09 capability-registry-benchmarks).
//!
//! Extends the compile-time model catalog ([`crate::llm::catalog`]) with
//! independently-sourced benchmark scores, so the [`super::router::ModelRouter`]
//! can break cost/context ties using measured capability instead of catalog
//! order alone.
//!
//! The dataset in `src/llm/data/model_benchmarks.json` is hand-curated, not
//! scraped — see `src/llm/data/UPDATE.md` for why and how to refresh it.
//! Every entry MUST carry a `source_url` and `retrieved_date` per
//! docs/uar-next-fable.md §2.4 ("version every entry with a source URL +
//! retrieval date").

use std::collections::HashMap;
use std::sync::LazyLock;

use serde::{Deserialize, Serialize};

/// Embedded benchmark dataset JSON. Unlike [`super::catalog::CATALOG_JSON`]
/// this is NOT generated by `build.rs` — it's a hand-curated file included
/// directly from the source tree, so editing it takes effect on the next
/// normal compile with no build-script step.
const BENCHMARKS_JSON: &str = include_str!("data/model_benchmarks.json");

/// Which capability dimension a benchmark measures.
///
/// Deliberately an open set of dimensions (not one field per benchmark) so
/// new benchmarks can be added under an existing dimension, or a new
/// dimension added, without a schema migration.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BenchmarkDimension {
    /// Software-engineering / code-generation capability (e.g. SWE-bench Verified).
    Coding,
    /// Multi-step tool-use / agentic task completion (e.g. GAIA, Terminal-Bench).
    Agentic,
    /// Effective (not just advertised) long-context recall (e.g. MRCR, RULER).
    Context,
}

/// A single sourced benchmark measurement for one model.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BenchmarkScore {
    /// Benchmark name (e.g. `"swe-bench-verified"`).
    pub benchmark: String,
    /// Which capability dimension this benchmark measures.
    pub dimension: BenchmarkDimension,
    /// Score as reported by the source, on the source's own scale (SWE-bench
    /// Verified etc. report 0.0-100.0 percentages).
    pub score: f64,
    /// URL of the leaderboard/source this score was read from.
    pub source_url: String,
    /// Date (`YYYY-MM-DD`) the score was retrieved/verified against the source.
    pub retrieved_date: String,
}

#[derive(Debug, Deserialize)]
struct BenchmarkDataset {
    models: HashMap<String, Vec<BenchmarkScore>>,
}

static BENCHMARKS: LazyLock<HashMap<String, Vec<BenchmarkScore>>> = LazyLock::new(|| {
    serde_json::from_str::<BenchmarkDataset>(BENCHMARKS_JSON)
        .unwrap_or_else(|e| {
            tracing::error!(error = %e, "Failed to parse embedded model benchmark dataset");
            BenchmarkDataset {
                models: HashMap::new(),
            }
        })
        .models
});

/// Look up all sourced benchmark scores for a `provider/model` id.
///
/// Returns an empty slice (not an error) when the model has no benchmark
/// data — most catalog entries won't, since coverage is deliberately a small
/// verified subset rather than a guessed-at-scale table (see
/// `src/llm/data/model_benchmarks.json`'s `_readme`).
#[must_use]
pub fn scores_for(model: &str) -> &'static [BenchmarkScore] {
    BENCHMARKS
        .get(model)
        .map_or(&[], |scores| scores.as_slice())
}

/// Best known score for a `provider/model` id on the given dimension, if any.
#[must_use]
pub fn best_score(model: &str, dimension: BenchmarkDimension) -> Option<f64> {
    scores_for(model)
        .iter()
        .filter(|s| s.dimension == dimension)
        .map(|s| s.score)
        .fold(None, |acc, score| match acc {
            Some(best) if best >= score => Some(best),
            _ => Some(score),
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_model_has_coding_score() {
        let score = best_score("anthropic/claude-opus-4-8", BenchmarkDimension::Coding);
        assert!(score.is_some());
        assert!(score.unwrap() > 0.0);
    }

    #[test]
    fn unknown_model_has_no_score() {
        assert!(scores_for("nonexistent-provider/nope-model").is_empty());
        assert!(
            best_score(
                "nonexistent-provider/nope-model",
                BenchmarkDimension::Coding
            )
            .is_none()
        );
    }

    #[test]
    fn unpopulated_dimension_is_none_not_zero() {
        // Agentic/context are intentionally unpopulated as of this pass —
        // must be None, not silently 0.0 (which would look like a real
        // measured "worst possible score" rather than "no data").
        assert!(
            best_score("anthropic/claude-opus-4-8", BenchmarkDimension::Agentic).is_none(),
            "agentic dimension should have no seeded data yet"
        );
    }

    #[test]
    fn every_entry_has_a_source_and_date() {
        for scores in BENCHMARKS.values() {
            for s in scores {
                assert!(!s.source_url.is_empty(), "missing source_url: {s:?}");
                assert!(
                    !s.retrieved_date.is_empty(),
                    "missing retrieved_date: {s:?}"
                );
            }
        }
    }
}
